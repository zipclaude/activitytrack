# Release step (owner, 2026-10-19: before every release check whether the
# manual needs updating): fails when
#   - a manual does not carry the version of the tag,
#   - the documentation did not change since the previous tag,
#   - an image the documents reference is missing.
# A version listed in scripts/manual-unchanged skips the checks: the owner
# chose to release it with the previous manual.
#
#   scripts/check-manual.sh v0.6.0

set -eu
cd "$(dirname "$0")/.."

TAG=$1
VERSION=${TAG#v}
fail=0

# a release listed in scripts/manual-unchanged keeps the previous manual (owner, 2026-10-23)
if grep -qx "$VERSION" scripts/manual-unchanged 2>/dev/null; then
	echo "manual left unchanged for $VERSION (scripts/manual-unchanged)"
	exit 0
fi

for f in docs/manual/it/manual.md docs/manual/it/quickstart.md docs/manual/en/manual.md docs/manual/en/quickstart.md \
	docs/manual/*/connectors/*.md; do
	[ -f "$f" ] || continue
	if ! head -n 12 "$f" | grep -q "\b$VERSION\b"; then
		echo "::error file=$f::the document does not mention version $VERSION in its first lines"
		fail=1
	fi
	dir=$(dirname "$f")
	for img in $(grep -o '!\[[^]]*\]([^)]*)' "$f" | sed 's/.*(\([^)]*\))/\1/'); do
		case "$img" in diagrams/*) continue ;; esac	# generated by the build
		if [ ! -f "$dir/$img" ]; then
			echo "::error file=$f::missing image $img"
			fail=1
		fi
	done
done

PREV=$(git describe --tags --abbrev=0 "$TAG^" 2>/dev/null || true)
if [ -n "$PREV" ] && git diff --quiet "$PREV" "$TAG" -- docs/manual; then
	echo "::error::docs/manual unchanged since $PREV: update the manual for $VERSION"
	fail=1
fi

[ $fail -eq 0 ] && echo "manual ok for $VERSION (previous tag: ${PREV:-none})"
exit $fail
